const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH || '/root/.cache/ms-playwright/chromium-1161/chrome-linux/chrome',args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page = await browser.newPage({viewport:{width:1440,height:900}});
  await page.goto('http://127.0.0.1:3100');
  await page.waitForTimeout(3000);
  await page.locator('#products').scrollIntoViewIfNeeded();
  await page.mouse.move(0,0);
  await page.waitForTimeout(500);
  const track = page.locator('#products .conveyor');
  const before = await track.evaluate(e => e.scrollLeft);
  await page.waitForTimeout(1000);
  assert.ok(await track.evaluate(e => e.scrollLeft) > before, 'Conveyor should move');
  await page.getByRole('button',{name:'Pause products',exact:true}).click();
  const paused = await track.evaluate(e => e.scrollLeft);
  await page.waitForTimeout(400);
  assert.equal(await track.evaluate(e => e.scrollLeft),paused);
  await page.locator('.model-feature').scrollIntoViewIfNeeded();
  await page.waitForTimeout(1500);
  await page.getByRole('button',{name:'Rotate model right'}).click();
  await page.waitForTimeout(300);
  const canvas = page.locator('.model-feature canvas');
  const first = await canvas.evaluate(e => e.toDataURL());
  await page.getByRole('button',{name:'Rotate model right'}).click();
  await page.waitForTimeout(300);
  assert.notEqual(await canvas.evaluate(e => e.toDataURL()), first, 'Rotation changes canvas');
  await page.screenshot({path:'/tmp/oanro-checks/model.png'});
  await page.locator('.highlight-photo').scrollIntoViewIfNeeded();
  await page.waitForTimeout(1200);
  await page.screenshot({path:'/tmp/oanro-checks/texture.png'});
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(() => window.scrollTo(0,0));
  await page.getByRole('button',{name:'Toggle navigation'}).click();
  await page.getByRole('button',{name:'Products',exact:true}).click();
  await page.locator('#menu-Products').getByRole('link',{name:'The Forest Knit',exact:true}).click();
  await page.waitForURL('**/products/forest-knit');
  await page.screenshot({path:'/tmp/oanro-checks/detail-mobile.png',fullPage:true});
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto('http://127.0.0.1:3100');
  await page.locator('#products').scrollIntoViewIfNeeded();
  await page.waitForTimeout(400);
  const reduced = await track.evaluate(e=>e.scrollLeft);
  await page.waitForTimeout(600);
  assert.equal(await track.evaluate(e=>e.scrollLeft),reduced);
  console.log('Conveyor autoplay/pause, 3D rotation, mobile navigation, reduced motion: PASS');
  await browser.close();
})().catch(error=>{console.error(error);process.exit(1);});
